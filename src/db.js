import { config } from './config.js';

// Banco PostgreSQL. Em produção, DATABASE_URL aponta para o Postgres (ex.: Neon).
// Sem DATABASE_URL (desenvolvimento, simulação e testes), usa o PGlite: um Postgres embutido,
// em memória ou na pasta indicada em PGLITE_DIR.
async function conectar() {
  if (config.databaseUrl) {
    const { default: pg } = await import('pg');
    const pool = new pg.Pool({ connectionString: config.databaseUrl, max: 5, idleTimeoutMillis: 30_000 });
    pool.on('error', (e) => console.error('Erro na conexão com o banco:', e.message));
    return { query: (sql, params) => pool.query(sql, params), fechar: () => pool.end() };
  }
  const { PGlite } = await import('@electric-sql/pglite');
  const lite = new PGlite(process.env.PGLITE_DIR || undefined);
  return { query: (sql, params) => lite.query(sql, params), fechar: () => lite.close() };
}

const ESQUEMA = `
  CREATE TABLE IF NOT EXISTS leads (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canal text NOT NULL,                 -- whatsapp | instagram
    contato text NOT NULL,               -- telefone (wa_id) ou IG-scoped id
    nome text,
    origem_ref text,                     -- código do post/campanha
    origem_post text,                    -- media id do Instagram, se houver
    area text,
    status text NOT NULL DEFAULT 'novo', -- novo | em_triagem | qualificado | com_advogado | descartado | optout
    resumo text,
    dados_json text,
    consentimento_lgpd integer NOT NULL DEFAULT 0,
    ia_ativa integer NOT NULL DEFAULT 1,
    followups_enviados integer NOT NULL DEFAULT 0,
    ultima_msg_lead timestamptz,
    ultima_msg_escritorio timestamptz,
    criado_em timestamptz NOT NULL DEFAULT now(),
    UNIQUE (canal, contato)
  );
  CREATE TABLE IF NOT EXISTS mensagens (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id integer NOT NULL REFERENCES leads(id),
    autor text NOT NULL,                 -- lead | ia | humano
    texto text NOT NULL,
    criado_em timestamptz NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS mensagens_lead_idx ON mensagens (lead_id, id);
  CREATE TABLE IF NOT EXISTS posts (
    media_id text PRIMARY KEY,           -- ID da mídia no Instagram (post, reel ou anúncio)
    ref text NOT NULL UNIQUE,            -- código usado no link do WhatsApp (ex.: AR001)
    tema text NOT NULL,
    permalink text,
    legenda text,
    publicado_em timestamptz,
    analisado_em timestamptz
  );
  CREATE TABLE IF NOT EXISTS comentarios (
    id text PRIMARY KEY,                 -- ID do comentário no Instagram
    media_id text NOT NULL REFERENCES posts(media_id),
    autor_id text,
    autor_usuario text,
    texto text NOT NULL,
    comentado_em timestamptz NOT NULL,
    temperatura text,                    -- quente | morno | frio | fora_do_escopo
    beneficio text,
    motivo text,
    resposta_publica text,               -- sugestão da IA, editável
    mensagem_privada text,               -- sugestão da IA, editável
    status text NOT NULL DEFAULT 'pendente', -- pendente | enviado | ignorado | expirado | erro
    decidido_por text,
    decidido_em timestamptz,
    erro text
  );
  CREATE INDEX IF NOT EXISTS comentarios_post_idx ON comentarios (media_id, status);
  CREATE TABLE IF NOT EXISTS eventos_processados (
    id text PRIMARY KEY,
    criado_em timestamptz NOT NULL DEFAULT now()
  );
`;

let pronto;
function banco() {
  pronto ??= conectar().then(async (b) => {
    for (const comando of ESQUEMA.split(';').map((s) => s.trim()).filter(Boolean)) await b.query(comando);
    return b;
  });
  return pronto;
}

async function linhas(sql, params = []) {
  return (await (await banco()).query(sql, params)).rows;
}
async function linha(sql, params = []) {
  return (await linhas(sql, params))[0];
}

/** Executa SQL arbitrário (usado em testes e manutenção). */
export const consultar = linhas;

export async function fecharBanco() {
  if (pronto) await (await pronto).fechar();
  pronto = undefined;
}

// Monta "a = $2, b = $3" a partir de um objeto; só aceita nomes de coluna simples.
function setDinamico(campos, inicio = 2) {
  const chaves = Object.keys(campos);
  for (const k of chaves) if (!/^[a-z_]+$/.test(k)) throw new Error(`coluna inválida: ${k}`);
  return { set: chaves.map((k, i) => `${k} = $${i + inicio}`).join(', '), valores: chaves.map((k) => campos[k]) };
}

// A Meta reenvia webhooks; isso garante que cada evento seja tratado uma vez só.
export async function jaProcessado(eventoId) {
  const r = await linhas('INSERT INTO eventos_processados (id) VALUES ($1) ON CONFLICT DO NOTHING RETURNING id', [eventoId]);
  return r.length === 0;
}

export function obterOuCriarLead({ canal, contato, nome, origemRef, origemPost }) {
  return linha(
    `INSERT INTO leads (canal, contato, nome, origem_ref, origem_post) VALUES ($1, $2, $3, $4, $5)
     ON CONFLICT (canal, contato) DO UPDATE SET
       nome = COALESCE(leads.nome, excluded.nome),
       origem_ref = COALESCE(leads.origem_ref, excluded.origem_ref),
       origem_post = COALESCE(leads.origem_post, excluded.origem_post)
     RETURNING *`,
    [canal, contato, nome ?? null, origemRef ?? null, origemPost ?? null],
  );
}

export function leadExistente(canal, contato) {
  return linha('SELECT * FROM leads WHERE canal = $1 AND contato = $2', [canal, contato]);
}

export async function registrarMensagem(leadId, autor, texto) {
  await linhas('INSERT INTO mensagens (lead_id, autor, texto) VALUES ($1, $2, $3)', [leadId, autor, texto]);
  await linhas(
    autor === 'lead'
      ? 'UPDATE leads SET ultima_msg_lead = now(), followups_enviados = 0 WHERE id = $1'
      : 'UPDATE leads SET ultima_msg_escritorio = now() WHERE id = $1',
    [leadId],
  );
}

export async function historico(leadId, limite = 40) {
  const r = await linhas('SELECT autor, texto FROM mensagens WHERE lead_id = $1 ORDER BY id DESC LIMIT $2', [leadId, limite]);
  return r.reverse();
}

export async function atualizarLead(leadId, campos) {
  if (Object.keys(campos).length === 0) return;
  const { set, valores } = setDinamico(campos);
  await linhas(`UPDATE leads SET ${set} WHERE id = $1`, [leadId, ...valores]);
}

export function listarLeads() {
  return linhas('SELECT * FROM leads ORDER BY id DESC');
}

export function leadsParaFollowup(aposHoras, maxTentativas) {
  // Só reengaja quem já conversou, deu consentimento, não pediu para sair
  // e ficou em silêncio depois da última resposta do escritório.
  return linhas(
    `SELECT * FROM leads
     WHERE canal = 'whatsapp'
       AND consentimento_lgpd = 1
       AND status IN ('novo', 'em_triagem')
       AND ia_ativa = 1
       AND followups_enviados < $1
       AND ultima_msg_escritorio IS NOT NULL
       AND (ultima_msg_lead IS NULL OR ultima_msg_lead < ultima_msg_escritorio)
       AND ultima_msg_escritorio <= now() - make_interval(hours => $2)`,
    [maxTentativas, aposHoras],
  );
}

export function leadPorId(id) {
  return linha('SELECT * FROM leads WHERE id = $1', [id]);
}

// ---------- posts e comentários ----------

export function salvarPost({ mediaId, ref, tema, permalink, legenda, publicadoEm }) {
  return linha(
    `INSERT INTO posts (media_id, ref, tema, permalink, legenda, publicado_em) VALUES ($1, $2, $3, $4, $5, $6)
     ON CONFLICT (media_id) DO UPDATE SET
       tema = excluded.tema, permalink = COALESCE(excluded.permalink, posts.permalink),
       legenda = COALESCE(excluded.legenda, posts.legenda), publicado_em = COALESCE(excluded.publicado_em, posts.publicado_em)
     RETURNING *`,
    [mediaId, ref, tema, permalink ?? null, legenda ?? null, publicadoEm ?? null],
  );
}

export function postPorMidia(mediaId) {
  return linha('SELECT * FROM posts WHERE media_id = $1', [mediaId]);
}

export function postPorRef(ref) {
  return linha('SELECT * FROM posts WHERE upper(ref) = upper($1)', [ref]);
}

export function listarPosts() {
  return linhas(
    `SELECT p.*,
       (SELECT count(*)::int FROM comentarios c WHERE c.media_id = p.media_id) AS comentarios,
       (SELECT count(*)::int FROM comentarios c WHERE c.media_id = p.media_id AND c.temperatura = 'quente') AS quentes,
       (SELECT count(*)::int FROM leads l WHERE l.origem_ref = p.ref) AS leads
     FROM posts p ORDER BY p.publicado_em DESC NULLS LAST`,
  );
}

export async function marcarPostAnalisado(mediaId) {
  await linhas('UPDATE posts SET analisado_em = now() WHERE media_id = $1', [mediaId]);
}

/** Insere comentários novos; devolve só os que ainda não existiam. */
export async function inserirComentarios(mediaId, lista) {
  const novos = [];
  for (const c of lista) {
    const r = await linhas(
      `INSERT INTO comentarios (id, media_id, autor_id, autor_usuario, texto, comentado_em)
       VALUES ($1, $2, $3, $4, $5, $6) ON CONFLICT DO NOTHING RETURNING id`,
      [c.id, mediaId, c.autorId ?? null, c.usuario ?? null, c.texto, c.criadoEm],
    );
    if (r.length) novos.push(c);
  }
  return novos;
}

export async function salvarClassificacao(id, c) {
  await linhas(
    `UPDATE comentarios SET temperatura = $2, beneficio = $3, motivo = $4, resposta_publica = $5, mensagem_privada = $6
     WHERE id = $1`,
    [id, c.temperatura, c.beneficio, c.motivo, c.resposta_publica, c.mensagem_privada],
  );
}

export function comentariosSemClassificacao(mediaId) {
  return linhas('SELECT * FROM comentarios WHERE media_id = $1 AND temperatura IS NULL', [mediaId]);
}

const ORDEM_TEMPERATURA = "CASE temperatura WHEN 'quente' THEN 0 WHEN 'morno' THEN 1 WHEN 'frio' THEN 2 ELSE 3 END";

// O Instagram só aceita resposta privada até 7 dias após o comentário.
export async function expirarComentarios() {
  await linhas(
    `UPDATE comentarios SET status = 'expirado'
     WHERE status = 'pendente' AND comentado_em < now() - interval '7 days'`,
  );
}

export async function comentariosDoPost(mediaId) {
  await expirarComentarios();
  return linhas(`SELECT * FROM comentarios WHERE media_id = $1 ORDER BY ${ORDEM_TEMPERATURA}, comentado_em DESC`, [mediaId]);
}

export function comentarioPorId(id) {
  return linha('SELECT * FROM comentarios WHERE id = $1', [id]);
}

export async function atualizarComentario(id, campos) {
  const { set, valores } = setDinamico(campos);
  await linhas(`UPDATE comentarios SET ${set} WHERE id = $1`, [id, ...valores]);
}
